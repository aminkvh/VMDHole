# ---- 19. <HetResidues>, which was left unported for a WRONG reason ----------
# The stated reason was "empty on every reference, so unvalidatable". Checking
# rather than remembering: hem_origin carries HEM 508 A on three of four tunnels
# and 1ERI carries DT 9 B then DA 6 B + DA 7 B. Both are compared, and the
