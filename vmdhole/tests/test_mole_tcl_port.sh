# ---- 22. a custom exit ALONGSIDE the regular openings -----------------------
# Every other custom-exit check runs with UseCustomExitsOnly. Without it,
# GetTunnels builds `sources` as the origin's cavity CONCATENATED with the
# SurfaceCavity and runs FilterTunnels over the COMBINED list - so the surface
# tunnel and the cavity's own tunnels compete for similarity. Gating the surface
# search on exits-only lost MOLE's 8.82 A tunnel entirely, and filtering the two
# groups apart kept a 13.82 A one MOLE removes. This reference has both.
REFMIX="$DIR/fixtures/mole_reference/mixed_exit"
if [ -x "$MOLE_ENGINE" ] && [ -f "$REFMIX/tunnels.csv" ]; then
    ORI5=$(awk '$6=="A" && ($7==308 || $7==309) {x+=$1;y+=$2;z+=$3;n++} \
               END{printf "%.6f %.6f %.6f", x/n, y/n, z/n}' "$FIX")
    "$MOLE_ENGINE" "$FIX" "$TMP/mix.txt" 3.0 1.25 8 5.0 0.0 0 \
        $ORI5 5.0 --exit=-22.841,-55.065,-20.445 > /dev/null 2>&1
    # IN ORDER, not as a sorted set: MOLE's TunnelComparer is
    # (Cavity.Id, Length) and the SurfaceCavity is Id 0, so its tunnel comes
    # FIRST. Our sort used to run before the surface branch appended, which put
    # it last - the set matched and the order did not, which a sorted
    # comparison would never have shown.
    got=$(awk '$1=="T"{printf "%.2f\n",$4}' "$TMP/mix.txt" | tr '\n' ' ')
    want=$(tail -n +2 "$REFMIX/tunnels.csv" | cut -d, -f2 | tr '\n' ' ')
    if [ "$got" = "$want" ]; then
        ok "custom exit + regular openings match MOLE, in order ($want)"
    else
        bad "mixed custom-exit run differs: got [$got] want [$want]"
    fi
else
    echo "  SKIP  no mixed custom-exit reference"
fi

