            ok "the het sphere search is inert because Radius is surface-distance"
        else
            bad "the het sphere search now REACHES atoms - mole_lining.c's reasoning is stale"
        fi
        sed 's/^/     /' "$TMP/out"
    fi
    # Openings against MOLE's own, tetrahedron index for tetrahedron index. Only
    # possible because the triangulation reproduces MOLE's cell order.
    if [ -f "$KX5" ] && [ -f "$REFKX5/openings.txt" ]; then
        MOLE_OPENING_DEBUG=1 "$MOLE_ENGINE" "$KX5" "$TMP/ko.txt" \
            2>"$TMP/op.log" >/dev/null
        if python3 "$DIR/mole_openings_truth.py" "$TMP/op.log" \
                "$REFKX5/openings.txt" > "$TMP/out" 2>&1; then
            ok "cavity openings match MOLE index for index (19 cavities)"
        else
