            bad "pure Tcl triangulation differs from MOLE"
        fi
        sed 's/^/     /' "$TMP/out"
    else
        echo "  SKIP  Tcl triangulation dump failed: $(tail -1 "$TMP/tcerr" 2>/dev/null)"
    fi

    # Coplanar start: DHTriangulation.Init rejects a first cell with MinorsQ
    # below 1e-7 and swaps in a later vertex. This is the ONE place the port
    # cannot follow MOLE, and deliberately - MOLE picks the replacement with a
    # time-seeded `new Random()` constructed INSIDE the loop
    # (DHTriangulation.cs:104-113), so its own output is not reproducible here.
    # We take vertices 4, 5, ... in order instead.
    #
    # So the check is the two things that remain true: the path is reached, and
    # both engines walk it identically. A fixture that stopped being degenerate
    # would pass everything below while testing nothing, so the warning count is
    # asserted first.
    CP="$DIR/fixtures/mole_atoms_coplanar.txt"
    if [ -f "$CP" ]; then
        "$TMP/dhdump" "$CP" > "$TMP/cp_c.cells" 2>"$TMP/cp_err"
        nswap=$(grep -c "coplanar" "$TMP/cp_err" 2>/dev/null || echo 0)
        if [ "$nswap" -ge 1 ]; then
            ok "the coplanar-start path is reached ($nswap swaps)"
        else
            bad "the coplanar fixture no longer starts degenerate - it tests nothing"
        fi
        if timeout 300 tclsh "$DIR/dh_cells.tcl" "$CP" > "$TMP/cp_tcl.cells" 2>/dev/null \
                && [ -s "$TMP/cp_c.cells" ] && cmp -s "$TMP/cp_c.cells" "$TMP/cp_tcl.cells"; then
            ok "C and Tcl agree cell for cell through the coplanar start"
        else
            bad "C and Tcl diverge on the coplanar start"
        fi
    else
        echo "  SKIP  no coplanar fixture"
    fi
else
    echo "  SKIP  dh dump did not build: $(tail -1 "$TMP/dherr")"
fi

