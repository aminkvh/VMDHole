    fi
    # 1KX5, the nucleosome: 21 of 60 tunnels carry het residues, up to six each,
    # which is far richer than either reference above. Paired by LENGTH because
    # the two engines differ on the tunnel SET here (57 against 60) - see
    #that divergence is NOT diagnosed.
